test('OS-managed ownership rejects a live peer and recovers a SIGKILL without stale-lock races', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'qb-lease-'));
  const child = Bun.spawn(['bun', 'tests/fixtures-lease.ts', dir], {
    stdout: 'pipe',
    stderr: 'pipe',
  });
  try {
    const reader = child.stdout.getReader();
    const result = await reader.read();
    expect(new TextDecoder().decode(result.value)).toContain('LEASED');
    expect(() => acquireLease(dir)).toThrow('Another process');
    child.kill('SIGKILL');
    await child.exited;
    const release = acquireLease(dir);
    expect(() => acquireLease(dir)).toThrow();
    release();
    const next = acquireLease(dir);
    next();
  } finally {
    child.kill();
    rmSync(dir, { recursive: true, force: true });
  }
});
test('out-of-band DDL fails closed until a reviewed migration reconciles it', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'qb-stale-')),
    db = openDatabase(join(dir, 'main.pglite'));
  try {
    await initializeBranch(db);
    const engine = await new BranchEngine(db, 'test').initialize();
    await engine.migration(
      '001',
      'CREATE TABLE tasks(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,title TEXT NOT NULL);',
      'test',
    );
    await expose(db, 'tasks', true, ['id', 'title']);
    await savePolicy(db, {
      resource: 'tasks',
      operation: 'select',
      roles: ['anonymous'],
      mode: 'permissive',
      using: { op: 'true' },
      check: { op: 'true' },
      enabled: true,
    });
    expect((await engine.read('tasks', {}, { sub: null, role: 'anonymous' })).data).toEqual([]);
    await db.exec('ALTER TABLE tasks ADD COLUMN sensitive TEXT');
    await expect(
      (async () => await engine.read('tasks', {}, { sub: null, role: 'anonymous' }))(),
    ).rejects.toThrow('Physical schema changed');
    await engine.migration(
      '002-reconcile',
      'CREATE INDEX tasks_title ON tasks(title);',
      'reviewer',
    );
    expect((await engine.read('tasks', {}, { sub: null, role: 'anonymous' })).data).toEqual([]);
  } finally {
    await db.close();
    rmSync(dir, { recursive: true, force: true });
  }
});
test('structured logging drops unknown credential and payload fields at runtime', () => {
  const original = console.log;
  let text = '';
  console.log = (value) => {
    text = String(value);
  };
  try {
    log({
      action: 'test',
      password: 'secret-password',
      authorization: 'Bearer secret',
      payload: { private: true },
    } as any);
  } finally {
    console.log = original;
  }
  expect(JSON.parse(text).action).toBe('test');
  expect(text).not.toContain('secret');
  expect(text).not.toContain('private');
});
