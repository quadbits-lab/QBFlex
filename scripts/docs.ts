import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import GithubSlugger from 'github-slugger';
import { routes, capabilities } from '@qb-flex/contracts';
const root = 'apps/docs/content';
mkdirSync(root, { recursive: true });
const write = (name: string, title: string, description: string, body: string) => {
  const value = `export const frontmatter = ${JSON.stringify({ title, description, section: 'Reference', slug: `reference/${name}`, order: 90 })};\n\n# ${title}\n\n${body}\n`;
  const path = join(root, 'reference', name + '.mdx');
  mkdirSync(join(root, 'reference'), { recursive: true });
  if (process.argv.includes('--check')) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== value)
      throw new Error(`Generated docs are stale: ${path}`);
  } else writeFileSync(path, value);
};
write(
  'management-api',
  'Management and REST API',
  'Routes generated from the shared contract registry.',
  `The Management API requires a platform session or management token. Project APIs require a publishable key and evaluate the application identity separately.\n\n| Method | Route | Purpose |\n| --- | --- | --- |\n${routes.map(([method, path, title]) => `| ${method} | \`${path}\` | ${title} |`).join('\n')}\n\n## Response envelope\n\nQB resource operations return \`{ data, meta }\`. Errors return \`{ error: { code, message, requestId, retryable } }\`. Auth endpoints retain Better Auth’s native response contract; binary downloads return bytes and OpenAPI returns a schema document. Schema-sensitive results include a schema version. Provisioning returns HTTP 202 and an operation ID; poll its status until succeeded or failed.\n\n## Availability\n\n${Object.entries(
    capabilities,
  )
    .map(([key, status]) => `- **${key}:** ${status}`)
    .join('\n')}`,
);
for (const [folder, name] of [
  ['sdk-js', 'vanilla-api'],
  ['sdk-react', 'react-api'],
]) {
  const dts = `packages/${folder}/dist/index.d.ts`;
  if (!existsSync(dts)) throw new Error('Build SDK declarations before generating documentation');
  write(
    name,
    folder === 'sdk-js' ? 'JavaScript client API' : 'React provider and hook API',
    'Public declarations generated from the SDK source.',
    `These declarations are generated by TypeScript from the same code used by the example applications.\n\n\`\`\`ts\n${readFileSync(dts, 'utf8')}\n\`\`\``,
  );
}
const files: string[] = [];
function scan(dir: string) {
  for (const item of readdirSync(dir, { withFileTypes: true }))
    item.isDirectory()
      ? scan(join(dir, item.name))
      : item.name.endsWith('.mdx') && files.push(join(dir, item.name));
}
scan(root);
const docs = files
  .map((file) => {
    const content = readFileSync(file, 'utf8');
    const meta = content.match(/export const frontmatter = (\{.*\});/);
    if (!meta) throw new Error(`Missing frontmatter: ${file}`);
    const frontmatter = JSON.parse(meta[1]!);
    const body = content.replace(meta[0], '');
    const slugger = new GithubSlugger();
    const headings = [...body.replace(/```[\s\S]*?```/g, '').matchAll(/^(#{1,6}) (.+)$/gm)]
      .map((m) => ({ title: m[2]!, id: slugger.slug(m[2]!), level: m[1]!.length }))
      .filter((heading) => heading.level > 1 && heading.level < 4);
    return {
      ...frontmatter,
      file: file.replace('apps/docs/', ''),
      headings,
      text: body.replace(/```\w*/g, '').replace(/[#*`<>]/g, ''),
    };
  })
  .sort((a, b) => a.order - b.order || a.slug.localeCompare(b.slug));
const slugs = new Set(docs.map((d) => d.slug));
if (slugs.size !== docs.length) throw new Error('Duplicate documentation slug');
for (const file of files) {
  const body = readFileSync(file, 'utf8');
  for (const match of body.matchAll(/\]\(\/docs\/([^\s)#]+)(?:#([^)]*))?\)/g)) {
    if (!slugs.has(match[1])) throw new Error(`Broken documentation link in ${file}: ${match[1]}`);
    if (
      match[2] &&
      !docs
        .find((document) => document.slug === match[1])!
        .headings.some((heading: { id: string }) => heading.id === match[2])
    )
      throw new Error(`Broken heading link in ${file}`);
  }
}
mkdirSync('apps/docs/src/generated', { recursive: true });
mkdirSync('apps/docs/public', { recursive: true });
const json = JSON.stringify(docs, null, 2) + '\n';
const manifest = 'apps/docs/src/generated/manifest.json';
if (process.argv.includes('--check')) {
  if (readFileSync(manifest, 'utf8') !== json) throw new Error('Documentation manifest is stale');
  if (
    readFileSync('apps/docs/public/benchmark.json', 'utf8') !==
    readFileSync('docs/benchmarks/linux-arm64.json', 'utf8')
  )
    throw new Error('Documentation benchmark asset is stale');
} else {
  writeFileSync(
    'apps/docs/public/benchmark.json',
    readFileSync('docs/benchmarks/linux-arm64.json'),
  );
  writeFileSync(manifest, json);
  writeFileSync(
    'apps/docs/public/search-index.json',
    JSON.stringify(
      docs.map(({ slug, title, text, section }) => ({ id: slug, slug, title, text, section })),
    ),
  );
  const origin = process.env.QB_DOCS_URL ?? 'http://localhost:7611';
  writeFileSync(
    'apps/docs/public/sitemap.xml',
    `<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"><url><loc>${origin}/</loc></url>${docs.map((d) => `<url><loc>${origin}/docs/${d.slug}</loc></url>`).join('')}</urlset>`,
  );
  writeFileSync(
    'apps/docs/public/robots.txt',
    `User-agent: *\nAllow: /\nSitemap: ${origin}/sitemap.xml\n`,
  );
}
console.log(`${docs.length} documentation pages checked.`);
