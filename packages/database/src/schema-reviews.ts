const digestOf = (sql: string) => createHash('sha256').update(JSON.stringify(sql)).digest('hex');

/** Classify destructive patterns. A parser alone does not prove safety. */
export function classifyDestructive(sql: string): DestructiveFinding[] {
  const findings: DestructiveFinding[] = [];
  const text = sql.replace(/--[^\n]*/g, ' ').replace(/\/\*[\s\S]*?\*\//g, ' ');
  if (/\bDROP\s+TABLE\b/i.test(text))
    findings.push({ kind: 'drop_table', detail: 'Contains DROP TABLE' });
  if (/\bDROP\s+COLUMN\b/i.test(text) || /\bALTER\s+TABLE\b[\s\S]*\bDROP\s+COLUMN\b/i.test(text))
    findings.push({ kind: 'drop_column', detail: 'Contains DROP COLUMN' });
  if (/\bALTER\s+TABLE\b[\s\S]*\bALTER\s+COLUMN\b[\s\S]*\bTYPE\b/i.test(text))
    findings.push({ kind: 'alter_type', detail: 'Contains ALTER COLUMN TYPE' });
  if (/\bTRUNCATE\b/i.test(text))
    findings.push({ kind: 'truncate', detail: 'Contains TRUNCATE' });
  if (/\bDELETE\s+FROM\b/i.test(text))
    findings.push({ kind: 'delete_rows', detail: 'Contains DELETE FROM' });
  if (/\bRENAME\b/i.test(text)) findings.push({ kind: 'rename', detail: 'Contains RENAME' });
  return findings;
}

/** Build an isolated in-memory clone of catalog DDL, exposure, relationships and policies. */
export async function cloneCatalog(source: BranchEngine) {
  await source.assertSchema();
  const tables = await schema(source.db);
  if (tables.length > 100)
    throw new QBError('LIMIT_EXCEEDED', 'Scratch supports at most 100 tables');
  const scratch = new Database(':memory:', { strict: true, safeIntegers: true });
  await scratch.exec(' ');
  await initializeBranch(scratch);
  const definitions: string[] = [];
  const constraints: string[] = [];
  for (const t of tables) {
    const columns = t.columns.map(
      (c) =>
        `${identifier(c.name)} ${c.type}${c.default?.startsWith('GENERATED') ? ' GENERATED BY DEFAULT AS IDENTITY' : c.default && !c.generated ? ' DEFAULT ' + c.default : ''}${c.generated ? ' GENERATED ALWAYS AS (' + c.default + ') STORED' : ''}${!c.nullable ? ' NOT NULL' : ''}`,
    );
    const keys = t.columns
      .filter((c) => c.primaryKey)
      .sort((a, b) => a.primaryKey - b.primaryKey);
    if (keys.length)
      columns.push('PRIMARY KEY (' + keys.map((c) => identifier(c.name)).join(',') + ')');
    const checks = await source.db
      .query(
        `SELECT pg_get_constraintdef(oid) AS sql,contype FROM pg_constraint WHERE conrelid=to_regclass($1) AND contype IN('c','f','u')`,
      )
      .all('public.' + identifier(t.name));
    for (const c of checks)
      if (c.contype === 'f')
        constraints.push(
          `ALTER TABLE ${identifier(t.name)} ADD ${c.sql.replace(/(?:NOT )?DEFERRABLE(?: INITIALLY (?:IMMEDIATE|DEFERRED))?/g, '')} DEFERRABLE INITIALLY DEFERRED`,
        );
      else columns.push(c.sql);
    definitions.push(`CREATE TABLE ${identifier(t.name)} (${columns.join(',')})`);
  }
  if (definitions.join('').length + constraints.join('').length > 1048576)
    throw new QBError('LIMIT_EXCEEDED', 'Scratch schema exceeds 1 MiB');
  for (const sql of definitions) await scratch.exec(sql);
  for (const sql of constraints) await scratch.exec(sql);
  await scratch
    .query("UPDATE _qb_meta SET value=? WHERE key='schema_version'")
    .run(String(await schemaVersion(source.db)));
  for (const table of tables)
    if (table.exposed) await expose(scratch, table.name, true, table.allowedColumns);
  for (const table of tables)
    for (const relationship of table.relationships ?? [])
      await registerRelationship(scratch, relationship);
  const engine = await new BranchEngine(scratch, crypto.randomUUID()).initialize();
  for (const policy of await policies(source.db)) await engine.savePolicy(policy);
  return { scratch, engine, tables };
}

interface ReviewRow {
  id: string;
  migration_id: string;
  digest: string;
  sql: string;
  base_schema_version: number | bigint;
  state: ReviewState;
  destructive: string;
  author: string;
  created_at: string;
  updated_at: string;
  applied_at: string | null;
  rehearsal_notes: string | null;
  type_check_ok: number | null;
}

/** Schema change reviews: draft → rehearsed → approved → applied | stale | rejected. */
export class SchemaReviews {
  constructor(private engine: BranchEngine) {}
  async initialize() {
    await this.engine.db.exec(`CREATE TABLE IF NOT EXISTS _qb_schema_reviews(
      id TEXT PRIMARY KEY,migration_id TEXT NOT NULL,digest TEXT NOT NULL,sql TEXT NOT NULL,
      base_schema_version BIGINT NOT NULL,state TEXT NOT NULL,destructive TEXT NOT NULL,
      author TEXT NOT NULL,created_at TEXT NOT NULL,updated_at TEXT NOT NULL,
      applied_at TEXT,rehearsal_notes TEXT,type_check_ok BIGINT);`);
    await this.engine.db.exec(
      `CREATE INDEX IF NOT EXISTS _qb_schema_reviews_state ON _qb_schema_reviews(state,created_at);`,
    );
    return this;
  }
  private summary(row: ReviewRow): SchemaReviewSummary {
    return {
      id: row.id,
      migrationId: row.migration_id,
      digest: row.digest,
      baseSchemaVersion: Number(row.base_schema_version),
      state: row.state,
      destructive: JSON.parse(row.destructive) as DestructiveFinding[],
      author: row.author,
      createdAt: row.created_at,
      updatedAt: row.updated_at,
      appliedAt: row.applied_at,
      rehearsalNotes: row.rehearsal_notes,
    };
  }
  private detail(row: ReviewRow): SchemaReviewDetail {
    return {
      ...this.summary(row),
      sql: row.sql,
      typeCheckOk: row.type_check_ok === null ? null : row.type_check_ok === 1,
    };
  }
  private async row(id: string): Promise<ReviewRow> {
    if (typeof id !== 'string' || id.length > 100)
      throw new QBError('VALIDATION', 'Invalid review identifier');
    const row = (await this.engine.db
      .query('SELECT * FROM _qb_schema_reviews WHERE id=?')
      .get(id)) as ReviewRow | null;
    if (!row) throw new QBError('NOT_FOUND', 'Schema review not found', 404);
    return row;
  }
  async list(): Promise<SchemaReviewSummary[]> {
    return (
      (await this.engine.db
        .query('SELECT * FROM _qb_schema_reviews ORDER BY created_at DESC LIMIT 100')
        .all()) as ReviewRow[]
    ).map((r) => this.summary(r));
  }
  async get(id: string): Promise<SchemaReviewDetail> {
    return this.detail(await this.row(id));
  }
  async create(input: SchemaReviewInput, author: string): Promise<SchemaReviewDetail> {
    if (
      !input ||
      typeof input.migrationId !== 'string' ||
      !/^[A-Za-z0-9_-]{1,100}$/.test(input.migrationId) ||
      typeof input.sql !== 'string' ||
      input.sql.length < 1 ||
      input.sql.length > 262144
    )
      throw new QBError('VALIDATION', 'Invalid schema review input');
    safeSQL(input.sql);
    const id = crypto.randomUUID();
    const now = new Date().toISOString();
    const digest = digestOf(input.sql);
    const base = await schemaVersion(this.engine.db);
    const destructive = classifyDestructive(input.sql);
    await this.engine.db
      .query(`INSERT INTO _qb_schema_reviews(
        id,migration_id,digest,sql,base_schema_version,state,destructive,author,created_at,updated_at,applied_at,rehearsal_notes,type_check_ok
      ) VALUES(?,?,?,?,?,'draft',?,?,?,?,NULL,NULL,NULL)`)
      .run(
        id,
        input.migrationId,
        digest,
        input.sql,
        base,
        JSON.stringify(destructive),
        author,
        now,
        now,
      );
    return this.get(id);
  }
  async rehearse(id: string): Promise<SchemaReviewDetail> {
    const row = await this.row(id);
    if (!['draft', 'rehearsed', 'stale'].includes(row.state))
      throw new QBError('CONFLICT', 'Review cannot be rehearsed from state ' + row.state, 409);
    const current = await schemaVersion(this.engine.db);
    if (Number(row.base_schema_version) !== current) {
      await this.engine.db
        .query(
          "UPDATE _qb_schema_reviews SET state='stale',updated_at=?,rehearsal_notes=? WHERE id=?",
        )
        .run(new Date().toISOString(), 'Base schema version changed', id);
      throw new QBError('SCHEMA_STALE', 'Review base schema version no longer matches', 409);
    }
    safeSQL(row.sql);
    let typeCheckOk = false;
    let notes = 'Rehearsal succeeded';
    const cloned = await cloneCatalog(this.engine);
    try {
      await cloned.engine.migration(row.migration_id, row.sql, 'rehearsal');
      const tables = await schema(cloned.scratch);
      const rpc = (
        (await cloned.scratch.query('SELECT definition FROM _qb_rpc').all()) as {
          definition: string;
        }[]
      ).map((r) => JSON.parse(r.definition));
      generateTypes(tables, await schemaVersion(cloned.scratch), rpc);
      typeCheckOk = true;
    } catch (error) {
      notes =
        error instanceof Error ? error.message.slice(0, 500) : 'Rehearsal failed';
      await this.engine.db
        .query(
          "UPDATE _qb_schema_reviews SET state='rejected',updated_at=?,rehearsal_notes=?,type_check_ok=0 WHERE id=?",
        )
        .run(new Date().toISOString(), notes, id);
      throw new QBError('VALIDATION', 'Rehearsal failed: ' + notes);
    } finally {
      await cloned.scratch.close();
    }
    await this.engine.db
      .query(
        "UPDATE _qb_schema_reviews SET state='rehearsed',updated_at=?,rehearsal_notes=?,type_check_ok=? WHERE id=?",
      )
      .run(new Date().toISOString(), notes, typeCheckOk ? 1 : 0, id);
    return this.get(id);
  }
  async approve(id: string): Promise<SchemaReviewDetail> {
    const row = await this.row(id);
    if (row.state !== 'rehearsed')
      throw new QBError('CONFLICT', 'Only rehearsed reviews can be approved', 409);
    const current = await schemaVersion(this.engine.db);
    if (Number(row.base_schema_version) !== current || row.digest !== digestOf(row.sql)) {
      await this.engine.db
        .query("UPDATE _qb_schema_reviews SET state='stale',updated_at=? WHERE id=?")
        .run(new Date().toISOString(), id);
      throw new QBError('SCHEMA_STALE', 'Review is stale relative to the live branch', 409);
    }
    await this.engine.db
      .query("UPDATE _qb_schema_reviews SET state='approved',updated_at=? WHERE id=?")
      .run(new Date().toISOString(), id);
    return this.get(id);
  }
  async reject(id: string): Promise<SchemaReviewDetail> {
    const row = await this.row(id);
    if (['applied', 'rejected'].includes(row.state))
      throw new QBError('CONFLICT', 'Review is already terminal', 409);
    await this.engine.db
      .query("UPDATE _qb_schema_reviews SET state='rejected',updated_at=? WHERE id=?")
      .run(new Date().toISOString(), id);
    return this.get(id);
  }
  /** Apply an approved review to the live branch. Rejects stale digests/versions. */
  async applyApproved(id: string, author: string) {
    const row = await this.row(id);
    if (row.state !== 'approved')
      throw new QBError('CONFLICT', 'Migration requires an approved schema review', 409);
    const current = await schemaVersion(this.engine.db);
    if (Number(row.base_schema_version) !== current || row.digest !== digestOf(row.sql)) {
      await this.engine.db
        .query("UPDATE _qb_schema_reviews SET state='stale',updated_at=? WHERE id=?")
        .run(new Date().toISOString(), id);
      throw new QBError('SCHEMA_STALE', 'Approved review is stale', 409);
    }
    const result = await this.engine.migration(row.migration_id, row.sql, author);
    await this.engine.db
      .query(
        "UPDATE _qb_schema_reviews SET state='applied',updated_at=?,applied_at=? WHERE id=?",
      )
      .run(new Date().toISOString(), new Date().toISOString(), id);
    return result;
  }
  async requireApproved(migrationId: string, sql: string) {
    const digest = digestOf(sql);
    const row = (await this.engine.db
      .query(
        "SELECT * FROM _qb_schema_reviews WHERE migration_id=? AND digest=? AND state='approved' ORDER BY created_at DESC LIMIT 1",
      )
      .get(migrationId, digest)) as ReviewRow | null;
    if (!row)
      throw new QBError(
        'REVIEW_REQUIRED',
        'Live migrations require an approved schema review with a matching digest',
        409,
      );
    return row.id;
  }
}
