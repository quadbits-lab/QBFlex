import { Database } from './connection';
import { QBError, type Identity, type Operation, type Query } from '@qb-flex/contracts';
import {
  initializeBranch,
  schema,
  schemaVersion,
  expose,
  policies,
  registerRelationship,
} from '@qb-flex/schema';
import { identifier } from '@qb-flex/policies';
import { BranchEngine } from './engine';
export interface PolicySimulation {
  table: string;
  operation: Operation;
  identity: Identity;
  fixtures?: Record<string, Record<string, unknown>[]>;
  query?: Query;
  input?: unknown;
  key?: string;
  revision?: number;
}
/** No source row images, identity tables, custom triggers, tokens or jobs are copied. */
export async function simulatePolicy(source: BranchEngine, input: PolicySimulation) {
  const roles = Array.isArray(input.identity?.roles) ? input.identity.roles : [];
  if (
    !input ||
    !['select', 'insert', 'update', 'delete'].includes(input.operation) ||
    !['anonymous', 'authenticated'].includes(input.identity?.role) ||
    roles.some((r) => typeof r !== 'string' || r.length > 64) ||
    (input.identity.sub !== null &&
      (typeof input.identity.sub !== 'string' || input.identity.sub.length > 200)) ||
    (input.identity.role === 'authenticated' && !input.identity.sub) ||
    (input.identity.role === 'anonymous' && (input.identity.sub !== null || roles.length > 0))
  )
    throw new QBError('VALIDATION', 'Invalid synthetic operation or identity');
  input.identity = { ...input.identity, roles };
  if (Buffer.byteLength(JSON.stringify(input)) > 1048576)
    throw new QBError('VALIDATION', 'Simulation input exceeds 1 MiB');
  await source.assertSchema();
  source.table(input.table);
  const tables = await schema(source.db);
  if (tables.length > 100)
    throw new QBError('LIMIT_EXCEEDED', 'Simulation supports at most 100 tables');
  const fixtures = input.fixtures ?? {};
  if (!fixtures || typeof fixtures !== 'object' || Array.isArray(fixtures))
    throw new QBError('VALIDATION', 'Fixtures must map table names to row arrays');
  let count = 0;
  for (const [name, rows] of Object.entries(fixtures)) {
    if (!tables.some((t) => t.name === name) || !Array.isArray(rows))
      throw new QBError('VALIDATION', 'Invalid fixture table or rows');
    count += rows.length;
  }
  if (count > 1000)
    throw new QBError('LIMIT_EXCEEDED', 'Simulation supports at most 1,000 fixture rows');
  const scratch = new Database(':memory:', { strict: true, safeIntegers: true });
  try {
    await scratch.exec(' ');
    await initializeBranch(scratch);
    const definitions: string[] = [];
    const constraints: string[] = [];
    for (const t of tables) {
      const columns = t.columns.map(
        (c) =>
          `${identifier(c.name)} ${c.type}${c.default?.startsWith('GENERATED') ? ' GENERATED BY DEFAULT AS IDENTITY' : c.default && !c.generated ? ' DEFAULT ' + c.default : ''}${c.generated ? ' GENERATED ALWAYS AS (' + c.default + ') STORED' : ''}${!c.nullable ? ' NOT NULL' : ''}`,
      );
      const keys = t.columns
        .filter((c) => c.primaryKey)
        .sort((a, b) => a.primaryKey - b.primaryKey);
      if (keys.length)
        columns.push('PRIMARY KEY (' + keys.map((c) => identifier(c.name)).join(',') + ')');
      const checks = await source.db
        .query(
          `SELECT pg_get_constraintdef(oid) AS sql,contype FROM pg_constraint WHERE conrelid=to_regclass($1) AND contype IN('c','f','u')`,
        )
        .all('public.' + identifier(t.name));
      for (const c of checks)
        if (c.contype === 'f')
          constraints.push(
            `ALTER TABLE ${identifier(t.name)} ADD ${c.sql.replace(/(?:NOT )?DEFERRABLE(?: INITIALLY (?:IMMEDIATE|DEFERRED))?/g, '')} DEFERRABLE INITIALLY DEFERRED`,
          );
        else columns.push(c.sql);
      definitions.push(`CREATE TABLE ${identifier(t.name)} (${columns.join(',')})`);
    }
    if (definitions.join('').length + constraints.join('').length > 1048576)
      throw new QBError('LIMIT_EXCEEDED', 'Simulation schema exceeds 1 MiB');
    for (const sql of definitions) await scratch.exec(sql);
    for (const sql of constraints) await scratch.exec(sql);
    await scratch
      .query("UPDATE _qb_meta SET value=? WHERE key='schema_version'")
      .run(String(await schemaVersion(source.db)));
    for (const table of tables)
      if (table.exposed) await expose(scratch, table.name, true, table.allowedColumns);
    for (const table of tables)
      for (const relationship of table.relationships ?? [])
        await registerRelationship(scratch, relationship);
    const engine = await new BranchEngine(scratch, crypto.randomUUID()).initialize();
    for (const policy of await policies(source.db)) await engine.savePolicy(policy);
    await scratch
      .transaction(async (tx) => {
        await tx.exec('SET CONSTRAINTS ALL DEFERRED;');
        for (const [table, rows] of Object.entries(fixtures)) {
          for (let offset = 0; offset < rows.length; offset += 100)
            await engine.mutate(
              table,
              'insert',
              rows.slice(offset, offset + 100),
              { sub: null, role: 'anonymous', roles: [] },
              undefined,
              undefined,
              true,
            );
        }
        await tx.exec('SET CONSTRAINTS ALL IMMEDIATE');
      })
      .immediate();
    let oldRowAccess: boolean | null = null;
    if (input.operation === 'update' || input.operation === 'delete') {
      if (!input.key) throw new QBError('VALIDATION', 'Simulation requires a row key');
      const table = engine.table(input.table),
        key = engine.key(table, input.key);
      const policy = engine.policy(table, input.operation, input.identity);
      oldRowAccess = !!(await scratch
        .query(
          `SELECT 1 FROM ${identifier(table.name)} AS "qb_row_0" WHERE (${key.sql}) AND (${policy.sql})`,
        )
        .get(...([...key.params, ...policy.params] as any[])));
    }
    try {
      const result =
        input.operation === 'select'
          ? await engine.read(input.table, input.query ?? { limit: 10 }, input.identity)
          : await engine.mutate(
              input.table,
              input.operation,
              input.input,
              input.identity,
              input.key,
              undefined,
              false,
              input.revision,
            );
      return {
        allowed: true,
        oldRowAccess,
        prospectiveRowCheck: ['insert', 'update'].includes(input.operation) ? true : null,
        data: result.data,
        meta: result.meta,
      };
    } catch (error) {
      if (!(error instanceof QBError)) throw error;
      return {
        allowed: false,
        oldRowAccess,
        prospectiveRowCheck:
          error.code === 'DENIED' &&
          ['insert', 'update'].includes(input.operation) &&
          oldRowAccess !== false
            ? false
            : null,
        error: { code: error.code, message: error.message },
        data: [],
      };
    }
  } finally {
    await scratch.close();
  }
}
