import { Database } from './connection';
import { BranchEngine } from './engine';

const DEFAULT_TTL_HOURS = 72;
const MAX_TTL_HOURS = 168;

export function previewTtlHours(input?: number) {
  const hours = input ?? DEFAULT_TTL_HOURS;
  if (!Number.isInteger(hours) || hours < 1 || hours > MAX_TTL_HOURS)
    throw new QBError('VALIDATION', 'Preview TTL must be 1–168 hours');
  return hours;
}

/** Copy schema/policies/exposure/relationships into an empty durable branch directory. Never copies rows or auth. */
export async function provisionPreviewBranch(
  source: BranchEngine,
  path: string,
  fixtures: Record<string, Record<string, unknown>[]>,
) {
  mkdirSync(dirname(path), { recursive: true, mode: 0o700 });
  if (existsSync(path)) rmSync(path, { recursive: true, force: true });
  const tables = await schema(source.db);
  if (tables.length > 100)
    throw new QBError('LIMIT_EXCEEDED', 'Preview supports at most 100 tables');
  let fixtureCount = 0;
  for (const [name, rows] of Object.entries(fixtures)) {
    if (!tables.some((t) => t.name === name) || !Array.isArray(rows))
      throw new QBError('VALIDATION', 'Invalid fixture table or rows');
    fixtureCount += rows.length;
  }
  if (fixtureCount > 1000)
    throw new QBError('LIMIT_EXCEEDED', 'Preview supports at most 1,000 fixture rows');
  const db = new Database(path, { strict: true, safeIntegers: true });
  try {
    await db.exec(' ');
    await initializeBranch(db);
    const definitions: string[] = [];
    const constraints: string[] = [];
    for (const t of tables) {
      const columns = t.columns.map(
        (c) =>
          `${identifier(c.name)} ${c.type}${c.default?.startsWith('GENERATED') ? ' GENERATED BY DEFAULT AS IDENTITY' : c.default && !c.generated ? ' DEFAULT ' + c.default : ''}${c.generated ? ' GENERATED ALWAYS AS (' + c.default + ') STORED' : ''}${!c.nullable ? ' NOT NULL' : ''}`,
      );
      const keys = t.columns
        .filter((c) => c.primaryKey)
        .sort((a, b) => a.primaryKey - b.primaryKey);
      if (keys.length)
        columns.push('PRIMARY KEY (' + keys.map((c) => identifier(c.name)).join(',') + ')');
      const checks = await source.db
        .query(
          `SELECT pg_get_constraintdef(oid) AS sql,contype FROM pg_constraint WHERE conrelid=to_regclass($1) AND contype IN('c','f','u')`,
        )
        .all('public.' + identifier(t.name));
      for (const c of checks)
        if (c.contype === 'f')
          constraints.push(
            `ALTER TABLE ${identifier(t.name)} ADD ${c.sql.replace(/(?:NOT )?DEFERRABLE(?: INITIALLY (?:IMMEDIATE|DEFERRED))?/g, '')} DEFERRABLE INITIALLY DEFERRED`,
          );
        else columns.push(c.sql);
      definitions.push(`CREATE TABLE ${identifier(t.name)} (${columns.join(',')})`);
    }
    for (const sql of definitions) await db.exec(sql);
    for (const sql of constraints) await db.exec(sql);
    await db
      .query("UPDATE _qb_meta SET value=? WHERE key='schema_version'")
      .run(String(await schemaVersion(source.db)));
    for (const table of tables)
      if (table.exposed) await expose(db, table.name, true, table.allowedColumns);
    for (const table of tables)
      for (const relationship of table.relationships ?? [])
        await registerRelationship(db, relationship);
    const engine = await new BranchEngine(db, crypto.randomUUID()).initialize();
    for (const policy of await policies(source.db)) await engine.savePolicy(policy);
    if (fixtureCount) {
      await db
        .transaction(async (tx) => {
          await tx.exec('SET CONSTRAINTS ALL DEFERRED;');
          for (const [table, rows] of Object.entries(fixtures)) {
            for (let offset = 0; offset < rows.length; offset += 100)
              await engine.mutate(
                table,
                'insert',
                rows.slice(offset, offset + 100),
                { sub: null, role: 'anonymous', roles: [] },
                undefined,
                undefined,
                true,
              );
          }
          await tx.exec('SET CONSTRAINTS ALL IMMEDIATE');
        })
        .immediate();
    }
    await db.close(true);
  } catch (error) {
    try {
      await db.close(true);
    } catch {
      /* ignore */
    }
    rmSync(path, { recursive: true, force: true });
    throw error;
  }
}

export function previewSummary(row: {
  id: string;
  project_id: string;
  name: string;
  status: string;
  created_at: string;
  error?: string | null;
  expires_at?: string | null;
}): PreviewSummary {
  return {
    id: row.id,
    projectId: row.project_id,
    name: row.name,
    state: row.status as PreviewState,
    expiresAt: row.expires_at ?? row.created_at,
    createdAt: row.created_at,
    error: row.error ?? null,
  };
}

export function previewPath(dataDir: string, projectId: string, previewId: string) {
  for (const id of [projectId, previewId])
    if (!/^[a-f0-9-]{36}$/.test(id)) throw new QBError('INVALID_ID', 'Invalid resource identifier');
  return join(dataDir, 'projects', projectId, 'branches', previewId, 'main.pglite');
}
