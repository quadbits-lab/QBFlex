import { createHash } from 'node:crypto';
import {
  QBError,
  type IndexSuggestion,
  type QueryPlanResult,
  type QuerySample,
} from '@qb-flex/contracts';
import { identifier } from '@qb-flex/policies';
import type { BranchEngine } from './engine';

const MAX_SAMPLES = 200;
const LARGE_SCAN_ROWS = 1000;
const PLAN_SENTINEL = '__qb_plan__';
const FILTER_WORDS = new Set([
  'and',
  'or',
  'not',
  'null',
  'true',
  'false',
  'is',
  'in',
  'as',
  'on',
  'text',
  'integer',
  'bigint',
  'numeric',
  'boolean',
  'bool',
  'real',
  'double',
  'precision',
  'character',
  'varying',
  'varchar',
  'char',
  'timestamp',
  'date',
  'uuid',
  'jsonb',
  'json',
  'bytea',
  'smallint',
  'any',
  'array',
  'row',
]);

interface SampleRow {
  id: string;
  fingerprint: string;
  table_name: string;
  duration_ms: number | bigint;
  sampled_at: number | bigint;
  hit_count: number | bigint;
  plan_sql: string;
}

function invalid(message: string): never {
  throw new QBError('VALIDATION', message);
}

/** Replace literals so stored fingerprints cannot retain parameter values. */
function redactFingerprint(value: string): string {
  const redacted = value
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/--[^\n]*/g, ' ')
    .replace(/\$([A-Za-z_][A-Za-z0-9_]*)?\$[\s\S]*?\$\1\$/g, '?')
    .replace(/'(?:''|[^'])*'/g, '?')
    .replace(/\$([1-9]\d*)\b/g, '?')
    .replace(/\b\d+(?:\.\d+)?\b/g, '?')
    .replace(/\s+/g, ' ')
    .trim();
  if (redacted.length > 500) return createHash('sha256').update(redacted).digest('hex');
  return redacted;
}

function redactPlanSql(sql: string): string {
  return sql
    .replace(/\$([A-Za-z_][A-Za-z0-9_]*)?\$[\s\S]*?\$\1\$/g, '?')
    .replace(/'(?:''|[^'])*'/g, '?')
    .replace(/\$([1-9]\d*)\b/g, '?')
    .trim();
}

function statementCode(sql: string): string {
  return sql
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/--[^\n]*/g, ' ')
    .replace(/'(?:''|[^'])*'/g, ' ')
    .replace(/"(?:""|[^"])*"/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

function assertGeneratedSelect(sql: string, table: string): string {
  const trimmed = sql.trim().replace(/;+\s*$/, '');
  if (!trimmed || trimmed.includes(';'))
    throw new QBError('VALIDATION', 'Query inspector only plans a single generated SELECT');
  const code = statementCode(trimmed);
  if (!code.startsWith('select'))
    throw new QBError('VALIDATION', 'Query inspector only plans a single generated SELECT');
  if (
    /\b(insert|update|delete|drop|alter|create|truncate|grant|revoke|copy|call|do|execute|prepare|into|set|reset)\b/.test(
      code,
    )
  )
    throw new QBError('VALIDATION', 'Query inspector rejects statements that are not generated SELECT queries');
  identifier(table);
  if (!new RegExp(`\\bfrom\\s+"${table}"\\s+as\\s+"qb_row_0"(?!\\w)`, 'i').test(trimmed))
    throw new QBError('VALIDATION', 'Query inspector only plans SELECT statements generated by the engine');
  if (/_qb_|information_schema|\bpg_/i.test(trimmed))
    throw new QBError('VALIDATION', 'Query inspector rejects reserved objects');
  return trimmed;
}

function filterColumns(filter: string): string[] {
  const columns: string[] = [];
  for (const match of filter.matchAll(/"([A-Za-z_][A-Za-z0-9_]*)"|\b([A-Za-z_][A-Za-z0-9_]*)\b/g)) {
    const name = match[1] ?? match[2];
    if (!name || FILTER_WORDS.has(name.toLowerCase())) continue;
    if (name.startsWith('qb_row') || name.startsWith('_qb')) continue;
    if (!columns.includes(name)) columns.push(name);
  }
  return columns;
}

function suggestionsFrom(plan: unknown): IndexSuggestion[] {
  const suggestions: IndexSuggestion[] = [];
  const seen = new Set<string>();
  const visit = (node: unknown) => {
    if (!node || typeof node !== 'object') return;
    const record = node as Record<string, unknown>;
    if (record['Node Type'] === 'Seq Scan') {
      const rows = Number(record['Plan Rows'] ?? 0);
      const filter = typeof record.Filter === 'string' ? record.Filter : '';
      const table = typeof record['Relation Name'] === 'string' ? record['Relation Name'] : '';
      const columns = filter ? filterColumns(filter) : [];
      const key = `${table}:${columns.join(',')}`;
      if (table && columns.length && rows >= LARGE_SCAN_ROWS && !seen.has(key)) {
        seen.add(key);
        suggestions.push({
          table,
          columns,
          reason: `Sequential scan estimates ${Math.round(rows)} rows and filters on ${columns.join(', ')}.`,
        });
      }
    }
    if (Array.isArray(record.Plans)) for (const child of record.Plans) visit(child);
  };
  const roots = Array.isArray(plan) ? plan : [plan];
  for (const root of roots) {
    if (root && typeof root === 'object' && 'Plan' in root) visit((root as { Plan: unknown }).Plan);
    else visit(root);
  }
  return suggestions;
}

/** Diagnostic samples and owner-side EXPLAIN plans. Never creates indexes or stores parameter values. */
export class QueryInspector {
  constructor(
    private engine: BranchEngine,
    private clock = Date.now,
  ) {}

  async initialize() {
    await this.engine.db.exec(`CREATE TABLE IF NOT EXISTS _qb_query_samples(
      id TEXT PRIMARY KEY,
      fingerprint TEXT NOT NULL UNIQUE,
      table_name TEXT NOT NULL,
      duration_ms BIGINT NOT NULL,
      sampled_at BIGINT NOT NULL,
      hit_count BIGINT NOT NULL,
      plan_sql TEXT NOT NULL);`);
    return this;
  }

  async recordSample(input: {
    table: string;
    fingerprint: string;
    durationMs: number;
    planSql: string;
  }): Promise<QuerySample> {
    if (!input || typeof input.table !== 'string') invalid('Invalid query sample');
    identifier(input.table);
    if (typeof input.fingerprint !== 'string' || !input.fingerprint.trim() || input.fingerprint.length > 4000)
      invalid('Invalid query fingerprint');
    if (
      typeof input.durationMs !== 'number' ||
      !Number.isFinite(input.durationMs) ||
      input.durationMs < 0 ||
      input.durationMs > 3_600_000
    )
      invalid('Invalid query duration');
    if (typeof input.planSql !== 'string' || !input.planSql.trim() || input.planSql.length > 8000)
      invalid('Invalid query plan SQL');
    const fingerprint = redactFingerprint(input.fingerprint);
    const planSql = redactPlanSql(input.planSql);
    if (!fingerprint || fingerprint.includes("'") || planSql.includes("'"))
      invalid('Query sample cannot retain parameter values');
    const now = this.clock();
    await this.engine.db
      .transaction(async (tx) => {
        await tx
          .query(
            `INSERT INTO _qb_query_samples(id,fingerprint,table_name,duration_ms,sampled_at,hit_count,plan_sql)
             VALUES(?,?,?,?,?,1,?)
             ON CONFLICT(fingerprint) DO UPDATE SET
               table_name=excluded.table_name,
               duration_ms=excluded.duration_ms,
               sampled_at=excluded.sampled_at,
               hit_count=_qb_query_samples.hit_count+1,
               plan_sql=excluded.plan_sql`,
          )
          .run(crypto.randomUUID(), fingerprint, input.table, Math.round(input.durationMs), now, planSql);
        await tx.exec(`DELETE FROM _qb_query_samples WHERE id NOT IN (
          SELECT id FROM _qb_query_samples ORDER BY sampled_at DESC, id DESC LIMIT ${MAX_SAMPLES})`);
      })
      .immediate();
    const row = await this.sampleByFingerprint(fingerprint);
    if (!row) throw new QBError('NOT_FOUND', 'Query sample not available', 404);
    return this.toSample(row);
  }

  async listSamples(): Promise<QuerySample[]> {
    const rows = (await this.engine.db
      .query('SELECT * FROM _qb_query_samples ORDER BY sampled_at DESC, id DESC LIMIT 200')
      .all()) as SampleRow[];
    return rows.map((row) => this.toSample(row));
  }

  async plan(fingerprint: string): Promise<QueryPlanResult> {
    if (typeof fingerprint !== 'string' || !fingerprint.trim() || fingerprint.length > 4000)
      invalid('Invalid query fingerprint');
    const normalized = redactFingerprint(fingerprint);
    const row = await this.sampleByFingerprint(normalized);
    if (!row) throw new QBError('NOT_FOUND', 'Query sample not available', 404);
    const queued: QueryPlanResult = {
      id: row.id,
      state: 'queued',
      fingerprint: row.fingerprint,
      plan: null,
      suggestions: [],
      error: null,
    };
    try {
      const sql = assertGeneratedSelect(row.plan_sql, row.table_name);
      const params = Array.from({ length: sql.match(/\?/g)?.length ?? 0 }, () => PLAN_SENTINEL);
      const explained = (await this.engine.db
        .query(`EXPLAIN (FORMAT JSON) ${sql}`)
        .get(...params)) as Record<string, unknown> | null;
      const column = explained?.['QUERY PLAN'] ?? explained?.['query plan'];
      if (column === undefined || column === null)
        throw new QBError('QUERY_PLAN_FAILED', 'EXPLAIN returned no plan');
      const parsed = typeof column === 'string' ? (JSON.parse(column) as unknown) : column;
      const plan = JSON.parse(JSON.stringify(parsed).split(PLAN_SENTINEL).join('?')) as unknown;
      return {
        ...queued,
        state: 'planned',
        plan,
        suggestions: suggestionsFrom(plan),
        error: null,
      };
    } catch (error) {
      return {
        ...queued,
        state: 'failed',
        plan: null,
        suggestions: [],
        error: error instanceof QBError ? error.message : 'Query plan failed',
      };
    }
  }

  private async sampleByFingerprint(fingerprint: string): Promise<SampleRow | null> {
    return (await this.engine.db
      .query('SELECT * FROM _qb_query_samples WHERE fingerprint=?')
      .get(fingerprint)) as SampleRow | null;
  }

  private toSample(row: SampleRow): QuerySample {
    return {
      id: row.id,
      fingerprint: row.fingerprint,
      table: row.table_name,
      operation: 'select',
      durationMs: Number(row.duration_ms),
      sampledAt: new Date(Number(row.sampled_at)).toISOString(),
      count: Number(row.hit_count),
    };
  }
}
