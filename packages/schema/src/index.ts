export async function initializeBranch(db: Database) {
  const hadObjectTimestamp = await db
    .query(
      "SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='_qb_objects' AND column_name='created_at'",
    )
    .get();
  await db.exec(`CREATE TABLE IF NOT EXISTS _qb_meta(key TEXT PRIMARY KEY,value TEXT NOT NULL);
    INSERT INTO _qb_meta VALUES('schema_version','1') ON CONFLICT DO NOTHING;
    CREATE TABLE IF NOT EXISTS _qb_migrations(id TEXT PRIMARY KEY,checksum TEXT NOT NULL,author TEXT NOT NULL,sql TEXT NOT NULL,applied_at TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS _qb_schema_exposure(table_name TEXT PRIMARY KEY,enabled BIGINT NOT NULL,allowed_columns TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS _qb_relationships(name TEXT NOT NULL,source TEXT NOT NULL,definition TEXT NOT NULL,PRIMARY KEY(name,source));
    CREATE TABLE IF NOT EXISTS _qb_rpc(name TEXT PRIMARY KEY,definition TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS _qb_policies(id TEXT PRIMARY KEY,resource TEXT NOT NULL,definition TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS _qb_outbox(seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,table_name TEXT NOT NULL,operation TEXT NOT NULL,pk_json TEXT NOT NULL,old_json TEXT,new_json TEXT,schema_version BIGINT NOT NULL,created_at TEXT NOT NULL DEFAULT(to_char(current_timestamp AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')));
    CREATE TABLE IF NOT EXISTS _qb_idempotency(scope TEXT PRIMARY KEY,hash TEXT NOT NULL,response TEXT NOT NULL,created_at TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS _qb_buckets(id TEXT PRIMARY KEY,name TEXT UNIQUE NOT NULL,visibility TEXT NOT NULL,max_size BIGINT NOT NULL,mime_rules TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS _qb_objects(id TEXT PRIMARY KEY,bucket_id TEXT NOT NULL REFERENCES _qb_buckets(id),key TEXT NOT NULL,owner_id TEXT NOT NULL,size BIGINT NOT NULL,mime TEXT NOT NULL,etag TEXT,state TEXT NOT NULL,created_at TEXT NOT NULL DEFAULT '',content_sha TEXT,expected_sha TEXT);
    CREATE UNIQUE INDEX IF NOT EXISTS _qb_objects_keys ON _qb_objects(bucket_id,key) WHERE state NOT IN('deleted','unavailable');
    CREATE INDEX IF NOT EXISTS _qb_objects_owner ON _qb_objects(owner_id,bucket_id);
    ALTER TABLE _qb_objects ADD COLUMN IF NOT EXISTS created_at TEXT NOT NULL DEFAULT '';
    ALTER TABLE _qb_objects ADD COLUMN IF NOT EXISTS content_sha TEXT;
    ALTER TABLE _qb_objects ADD COLUMN IF NOT EXISTS expected_sha TEXT;
    CREATE TABLE IF NOT EXISTS _qb_roles(id TEXT PRIMARY KEY,name TEXT UNIQUE NOT NULL,description TEXT NOT NULL DEFAULT '',created_at TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS _qb_user_roles(user_id TEXT NOT NULL,role_id TEXT NOT NULL REFERENCES _qb_roles(id) ON DELETE CASCADE,PRIMARY KEY(user_id,role_id));
    CREATE INDEX IF NOT EXISTS _qb_user_roles_role ON _qb_user_roles(role_id);

  `);
  if (!hadObjectTimestamp)
    await db.exec(
      `UPDATE _qb_objects SET created_at=to_char(current_timestamp AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') WHERE created_at=''`,
    );
}
export async function schemaVersion(db: Database) {
  return Number(
    (
      (await db.query("SELECT value FROM _qb_meta WHERE key='schema_version'").get()) as {
        value: string;
      }
    ).value,
  );
}
function enumValues(
  sql: string,
  column: {
    name: string;
    type: string;
  },
) {
  const name = column.name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const match = new RegExp(
    `CHECK\\s*\\(\\s*(?:"${name}"|${name})\\s+IN\\s*\\(([^)]*)\\)\\s*\\)`,
    'i',
  ).exec(sql);
  if (!match || column.type.toUpperCase() === 'BYTEA') return undefined;
  const tokens = match[1]!.match(/'(?:[^']|'')*'|-?\d+(?:\.\d+)?/g);
  if (
    !tokens ||
    tokens.length > 100 ||
    tokens.join('').replace(/\s/g, '') !== match[1]!.replace(/[,\s]/g, '')
  )
    return undefined;
  const values = tokens.map((token) =>
    token.startsWith("'")
      ? token.slice(1, -1).replaceAll("''", "'")
      : !token.includes('.') && !Number.isSafeInteger(Number(token))
        ? token
        : Number(token),
  );
  if (/INT|REAL|FLOAT|DOUBLE|NUMERIC|BOOL/i.test(column.type)) {
    if (values.some((value) => !Number.isFinite(Number(value)))) return undefined;
    return values.map((value) =>
      Number.isSafeInteger(Number(value)) || /REAL|FLOAT|DOUBLE/i.test(column.type)
        ? Number(value)
        : String(value),
    );
  }
  return values.map(String);
}
export async function schema(db: Database): Promise<TableSchema[]> {
  const tables = await db
    .query(
      `SELECT c.relname AS name FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE n.nspname='public' AND c.relkind='r' AND left(c.relname,4)<>'_qb_' ORDER BY c.relname`,
    )
    .all();
  const relations = await relationships(db);
  const result: TableSchema[] = [];
  for (const { name } of tables) {
    const exposure = await db
      .query('SELECT * FROM _qb_schema_exposure WHERE table_name=$1')
      .get(name);
    const columns = await db
      .query(
        `SELECT a.attname AS name,format_type(a.atttypid,a.atttypmod) AS type,
      NOT a.attnotnull AND NOT EXISTS(SELECT 1 FROM pg_index p WHERE p.indrelid=a.attrelid AND p.indisprimary AND a.attnum=ANY(p.indkey)) AS nullable,
      pg_get_expr(d.adbin,d.adrelid) AS "default",
      COALESCE((SELECT array_position(p.indkey::smallint[],a.attnum)+1 FROM pg_index p WHERE p.indrelid=a.attrelid AND p.indisprimary),0) AS "primaryKey",
      a.attgenerated<>'' AS generated, a.attidentity<>'' AS identity,
      (SELECT json_agg(e.enumlabel ORDER BY e.enumsortorder) FROM pg_enum e WHERE e.enumtypid=a.atttypid) AS enum
      FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid JOIN pg_namespace n ON n.oid=c.relnamespace
      LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
      WHERE n.nspname='public' AND c.relname=$1 AND a.attnum>0 AND NOT a.attisdropped ORDER BY a.attnum`,
      )
      .all(name);
    const checkDefinitions = await db
      .query(
        `SELECT pg_get_constraintdef(oid) AS sql FROM pg_constraint WHERE conrelid=to_regclass($1) AND contype='c'`,
      )
      .all('public.' + identifier(name));
    for (const c of columns) {
      for (const check of checkDefinitions) {
        const match =
          /^CHECK \(\("?([A-Za-z_][A-Za-z0-9_]*)"? = ANY \(ARRAY\[([\s\S]+)\]\)\)\)$/.exec(
            check.sql,
          );
        if (match && match[1] === c.name) {
          const literals = match[2].replace(
            /::(?:text|bigint|integer|numeric|character varying)/g,
            '',
          );
          c.enum = enumValues(`CHECK (${c.name} IN (${literals}))`, c);
        }
      }
    }
    for (const c of columns) {
      if (c.identity && c.default === null) c.default = 'GENERATED BY DEFAULT AS IDENTITY';
      delete c.identity;
      if (c.enum === null) delete c.enum;
    }
    const indexes = await db
      .query(
        `SELECT i.relname AS name,ix.indisunique::integer AS "unique",ix.indisprimary AS primary,
      pg_get_indexdef(ix.indexrelid) AS sql FROM pg_index ix JOIN pg_class t ON t.oid=ix.indrelid
      JOIN pg_class i ON i.oid=ix.indexrelid JOIN pg_namespace n ON n.oid=t.relnamespace WHERE n.nspname='public' AND t.relname=$1 ORDER BY i.relname`,
      )
      .all(name);
    const foreignKeys = await db
      .query(
        `SELECT con.oid::text AS id,k.ordinality-1 AS seq,other.relname AS "table",
      a.attname AS "from",b.attname AS "to" FROM pg_constraint con JOIN pg_class t ON t.oid=con.conrelid
      JOIN pg_namespace n ON n.oid=t.relnamespace JOIN pg_class other ON other.oid=con.confrelid
      CROSS JOIN LATERAL unnest(con.conkey,con.confkey) WITH ORDINALITY AS k(local,remote,ordinality)
      JOIN pg_attribute a ON a.attrelid=t.oid AND a.attnum=k.local
      JOIN pg_attribute b ON b.attrelid=other.oid AND b.attnum=k.remote
      WHERE con.contype='f' AND n.nspname='public' AND t.relname=$1 ORDER BY con.oid,k.ordinality`,
      )
      .all(name);
    result.push({
      name,
      columns,
      indexes,
      foreignKeys,
      exposed: !!exposure?.enabled,
      allowedColumns: exposure ? JSON.parse(exposure.allowed_columns) : columns.map((c) => c.name),
      relationships: relations.filter((r) => r.source === name),
    });
  }
  return result;
}
export const policies = async (db: Database): Promise<Policy[]> =>
  (
    (await db.query('SELECT definition FROM _qb_policies').all()) as {
      definition: string;
    }[]
  ).map((p) => JSON.parse(p.definition));
export async function savePolicy(
  db: Database,
  p: Policy,
  validate?: (expr: Policy['using']) => void,
) {
  const table = (await schema(db)).find((t) => t.name === p.resource);
  if (!table) throw new QBError('VALIDATION', 'Unknown table');
  if (
    !['select', 'insert', 'update', 'delete'].includes(p.operation) ||
    !['permissive', 'restrictive'].includes(p.mode) ||
    !Array.isArray(p.roles) ||
    !p.roles.length ||
    typeof p.enabled !== 'boolean'
  )
    throw new QBError('INVALID_POLICY', 'Invalid policy');
  const custom = ((await db.query('SELECT name FROM _qb_roles').all()) as { name: string }[]).map(
    (r) => r.name,
  );
  const allowed = new Set<string>([...SYSTEM_POLICY_ROLES, ...custom]);
  if (p.roles.some((r) => typeof r !== 'string' || !allowed.has(r)))
    throw new QBError('INVALID_POLICY', 'Invalid policy roles');
  for (const expr of [p.using, p.check])
    validate
      ? validate(expr)
      : compileExpression(
          expr,
          table.columns.map((c) => c.name),
          { sub: null, role: 'anonymous', roles: [] },
        );
  const id = p.id ?? crypto.randomUUID();
  await db
    .query(
      'INSERT INTO _qb_policies VALUES(?,?,?) ON CONFLICT(id) DO UPDATE SET resource=excluded.resource,definition=excluded.definition',
    )
    .run(id, p.resource, JSON.stringify({ ...p, id }));
  return { ...p, id };
}
export async function expose(db: Database, name: string, enabled: boolean, columns: string[]) {
  const table = (await schema(db)).find((t) => t.name === name);
  if (
    !table ||
    !table.columns.some((c) => c.primaryKey) ||
    typeof enabled !== 'boolean' ||
    !Array.isArray(columns) ||
    !columns.length ||
    columns.some((c) => !table.columns.some((x) => x.name === c)) ||
    table.columns.some((c) => c.primaryKey && !columns.includes(c.name))
  )
    throw new QBError(
      'VALIDATION',
      'Exposure requires a primary key and valid columns, including all primary keys',
    );
  if (
    table.columns.some(
      (c) =>
        !c.enum?.length &&
        !/^(?:text|character varying(?:\(\d+\))?|character(?:\(\d+\))?|smallint|integer|bigint|real|double precision|numeric(?:\(\d+(?:,\d+)?\))?|decimal|boolean|bytea|jsonb?|uuid|date|timestamp(?:\(\d+\))?(?: with(?:out)? time zone)?)$/i.test(
          c.type,
        ),
    )
  )
    throw new QBError(
      'UNSUPPORTED_TYPE',
      'Public exposure supports scalar PostgreSQL columns only',
    );
  const triggers = await db
    .query(
      `SELECT tgname FROM pg_trigger WHERE tgrelid=to_regclass($1) AND NOT tgisinternal AND left(tgname,12)<>'_qb_capture_'`,
    )
    .all('public.' + identifier(name));
  if (triggers.length)
    throw new QBError('UNSUPPORTED_TRIGGER', 'Tables with custom triggers cannot be exposed');
  await db
    .query(
      'INSERT INTO _qb_schema_exposure VALUES($1,$2,$3) ON CONFLICT(table_name) DO UPDATE SET enabled=excluded.enabled,allowed_columns=excluded.allowed_columns',
    )
    .run(name, Number(enabled), JSON.stringify(columns));
  const trigger = '_qb_capture_' + createHash('sha256').update(name).digest('hex').slice(0, 24);
  const triggerIdentifier = '"' + trigger + '"';
  await db.exec(`DROP TRIGGER IF EXISTS ${triggerIdentifier} ON ${identifier(name)}`);
  if (!enabled) return;
  const keys = table.columns
    .filter((c) => c.primaryKey)
    .sort((a, b) => a.primaryKey - b.primaryKey)
    .map((c) => c.name);
  const image = (row: string, names: string[]) =>
    `json_build_object(${names
      .map((n) => {
        const c = table.columns.find((c) => c.name === n)!,
          ref = `${row}.${identifier(n)}`;
        const value = /^(?:date|timestamp(?:\(\d+\))?(?: with(?:out)? time zone)?)$/i.test(c.type)
          ? `to_char(${ref} AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`
          : /^jsonb?$/i.test(c.type)
            ? `${ref}::text`
            : /^(?:numeric|decimal)(?:\(\d+(?:,\d+)?\))?$/i.test(c.type)
              ? `${ref}::text`
              : /^bytea$/i.test(c.type)
                ? `CASE WHEN ${ref} IS NULL THEN NULL ELSE 'qb_bytes:' || encode(${ref},'hex') END`
                : /^bigint$/i.test(c.type)
                  ? `CASE WHEN abs(${ref}::numeric)>9007199254740991 THEN to_json(${ref}::text) ELSE to_json(${ref}) END`
                  : /^boolean$/i.test(c.type)
                    ? `CASE WHEN ${ref} IS NULL THEN NULL ELSE ${ref}::integer END`
                    : ref;
        return `'${n}',${value}`;
      })
      .join(',')})::text`;
  await db.exec(`CREATE OR REPLACE FUNCTION ${triggerIdentifier}() RETURNS trigger LANGUAGE plpgsql AS $capture$
    BEGIN
      INSERT INTO _qb_outbox(table_name,operation,pk_json,old_json,new_json,schema_version)
      VALUES('${name}',lower(TG_OP),CASE WHEN TG_OP='DELETE' THEN ${image('OLD', keys)} ELSE ${image('NEW', keys)} END,
        CASE WHEN TG_OP='INSERT' THEN NULL ELSE ${image(
          'OLD',
          table.columns.map((c) => c.name),
        )} END,
        CASE WHEN TG_OP='DELETE' THEN NULL ELSE ${image(
          'NEW',
          table.columns.map((c) => c.name),
        )} END,
        (SELECT value::bigint FROM _qb_meta WHERE key='schema_version'));
      RETURN NULL;
    END $capture$;
    CREATE TRIGGER ${triggerIdentifier} AFTER INSERT OR UPDATE OR DELETE ON ${identifier(name)} FOR EACH ROW EXECUTE FUNCTION ${triggerIdentifier}()`);
}
export function generateTypes(
  tables: TableSchema[],
  version: number,
  rpc: {
    name: string;
    args: Record<string, string>;
    table: string;
  }[] = [],
) {
  const type = (c: TableSchema['columns'][number]) =>
    c.enum?.length
      ? c.enum.map((value) => JSON.stringify(value)).join(' | ')
      : /BOOL/i.test(c.type)
        ? '0 | 1'
        : /INT|NUMERIC|DECIMAL/i.test(c.type)
          ? 'number | string'
          : /REAL|FLOAT|DOUBLE/i.test(c.type)
            ? 'number'
            : 'string';
  const fields = (t: TableSchema, kind: string) =>
    t.columns
      .filter((c) => !c.generated || kind === 'Row')
      .map(
        (c) =>
          `    ${JSON.stringify(c.name)}${kind === 'Update' || (kind === 'Insert' && (c.nullable || c.default !== null)) ? '?' : ''}: ${type(c)}${c.nullable ? ' | null' : ''};`,
      )
      .join('\n');
  return `// Generated by QB Flex. Schema version ${version}.\nexport interface Database {\n${tables
    .filter((t) => t.exposed)
    .map(
      (t) =>
        `  ${JSON.stringify(t.name)}: {\n${['Row', 'Insert', 'Update'].map((k) => `    ${k}: {\n${fields({ ...t, columns: t.columns.filter((c) => t.allowedColumns.includes(c.name)) }, k)}\n    };`).join('\n')}\n    Relationships: { ${(
          t.relationships ?? []
        )
          .filter((r) => tables.some((t) => t.name === r.target && t.exposed))
          .map(
            (r) =>
              `${JSON.stringify(r.name)}: Database[${JSON.stringify(r.target)}]['Row']${r.cardinality === 'many' ? '[]' : ' | null'}`,
          )
          .join('; ')} };\n  };`,
    )
    .join('\n')}\n}\nexport interface RPC {\n${rpc
    .map(
      (r) =>
        `  ${JSON.stringify(r.name)}: { Args: { ${Object.entries(r.args)
          .map(([key, type]) => `${JSON.stringify(key)}: ${type}`)
          .join('; ')} }; Returns: Database[${JSON.stringify(r.table)}]['Row'][] };`,
    )
    .join('\n')}\n}\n`;
}
export const relationships = async (db: Database): Promise<Relationship[]> =>
  (
    (await db.query('SELECT definition FROM _qb_relationships').all()) as {
      definition: string;
    }[]
  ).map((r) => JSON.parse(r.definition));
export async function registerRelationship(db: Database, input: Relationship) {
  identifier(input.name);
  identifier(input.source);
  identifier(input.target);
  const tables = await schema(db),
    source = tables.find((t) => t.name === input.source),
    target = tables.find((t) => t.name === input.target);
  if (
    !source?.exposed ||
    !target?.exposed ||
    !source.allowedColumns.includes(input.localColumn) ||
    !target.allowedColumns.includes(input.foreignColumn) ||
    !['one', 'many'].includes(input.cardinality)
  )
    throw new QBError('VALIDATION', 'Relationships require exposed tables and columns');
  const direct = (source.foreignKeys as any[]).some(
    (f) => f.table === input.target && f.from === input.localColumn && f.to === input.foreignColumn,
  );
  const reverse = (target.foreignKeys as any[]).some(
    (f) => f.table === input.source && f.from === input.foreignColumn && f.to === input.localColumn,
  );
  if ((!direct && !reverse) || (input.cardinality === 'one' && !direct))
    throw new QBError('VALIDATION', 'Relationship must match a declared foreign key');
  await db
    .query(
      'INSERT INTO _qb_relationships VALUES(?,?,?) ON CONFLICT(name,source) DO UPDATE SET definition=excluded.definition',
    )
    .run(input.name, input.source, JSON.stringify(input));
  return input;
}
export async function registerRPC(db: Database, input: RPCOperation) {
  identifier(input.name);
  if (
    !['query', 'insert', 'update', 'delete'].includes(input.kind) ||
    !(await schema(db)).some((t) => t.name === input.table && t.exposed) ||
    !input.args ||
    Object.keys(input.args).length > 20 ||
    Object.values(input.args).some((t) => !['string', 'number', 'boolean'].includes(t))
  )
    throw new QBError('VALIDATION', 'Invalid reviewed RPC declaration');
  for (const name of Object.keys(input.args)) identifier(name);
  if (['update', 'delete'].includes(input.kind) && (!input.keyArg || !(input.keyArg in input.args)))
    throw new QBError('VALIDATION', 'Key argument required');
  await db
    .query(
      'INSERT INTO _qb_rpc VALUES(?,?) ON CONFLICT(name) DO UPDATE SET definition=excluded.definition',
    )
    .run(input.name, JSON.stringify(input));
  return input;
}
